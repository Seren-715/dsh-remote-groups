#!/usr/bin/env node
/**
 * Build-time Intelligent UI renderer packager.
 * Packs the audited offline renderer into src/generated/intelligent-ui-renderer-code.ts.
 * Never downloads or evaluates arbitrary model scripts at runtime.
 */
import { createRequire } from 'node:module'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const dest = resolve(here, '../src/generated/intelligent-ui-renderer-code.ts')
await mkdir(dirname(dest), { recursive: true })

const required = process.env.DSH_REQUIRE_INTELLIGENT_UI === '1'
  || process.env.DSH_REQUIRE_INTELLIGENT_UI === 'true'
  || process.argv.includes('--require')

let source = process.env.DSH_INTELLIGENT_UI_RENDERER_BUNDLE
if (!source) {
  try {
    source = require.resolve('deepseek-harness-intelligent-ui/renderer/renderer.js')
  } catch {
    // Sibling search for monorepo or side-by-side local checkout
    const candidates = [
      resolve(here, '../../../../DeepSeek-harness-intelligent-ui/renderer/renderer.js'),
      resolve(here, '../../../../deepseek-harness-intelligent-ui/renderer/renderer.js'),
      resolve(here, '../../../.deps/deepseek-harness-intelligent-ui/renderer/renderer.js'),
      resolve(here, '../../.deps/deepseek-harness-intelligent-ui/renderer/renderer.js'),
    ]
    for (const c of candidates) {
      if (existsSync(c)) {
        source = c
        break
      }
    }
  }
}

let bundled = ''
if (source && existsSync(source)) {
  bundled = await readFile(source, 'utf8')
  if (!bundled.includes('DshIntelligentUiRenderer') || !bundled.includes('mount') || !bundled.includes('render')) {
    throw new Error(`Intelligent UI renderer bundle at ${source} has an unexpected shape (missing DshIntelligentUiRenderer exports)`)
  }
} else if (required) {
  throw new Error('Intelligent UI renderer is required (DSH_REQUIRE_INTELLIGENT_UI=1 or --require), but no valid renderer.js was found!')
}

const output = '// Generated by scripts/build-intelligent-ui.mjs; do not hand-edit.\n'
  + 'export const INTELLIGENT_UI_RENDERER_CODE: string = ' + JSON.stringify(bundled) + '\n'

await writeFile(dest, output)
console.log(bundled
  ? `Intelligent UI: bundled offline renderer (${Math.round(bundled.length / 1024)} KB from ${source})`
  : 'Intelligent UI: optional renderer not installed (safe fallback)')
